// --- Auth (HMAC) -----------------------------------------------------------
//
// Vectors: RFC 4231 test case 1. Key = 20×0x0b, data = "Hi There".

func TestHMACVectors(t *testing.T) {
	key := repeat(0x0b, 20)
	data := []byte("Hi There")

	sha256Want := mustHex(t, "b0344c61d8db38535ca8afceaf0bf12b881dc200c9833da726e9376c2e32cff7")
	sha512Want := mustHex(t, "87aa7cdea5ef619d4ff0b4241a1d6cb02379f4e2ce4ec2787ad0b30545e17cdedaa833b7d6b8a702038b274eaea3f4e4be9d914eeb61f1702e696c203a126854")

	if got := NewHMACSHA256(key).Auth(data); !bytes.Equal(got, sha256Want) {
		t.Fatalf("hmac-sha256: %x", got)
	}
	if got := NewHMACSHA512(key).Auth(data); !bytes.Equal(got, sha512Want) {
		t.Fatalf("hmac-sha512: %x", got)
	}
	// HMAC-SHA-512-256 is HMAC-SHA-512 truncated to 32 bytes (libsodium crypto_auth).
	if got := NewHMACSHA512256(key).Auth(data); !bytes.Equal(got, sha512Want[:32]) {
		t.Fatalf("hmac-sha512256: %x", got)
	}
}

