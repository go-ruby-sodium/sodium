func TestErrorTree(t *testing.T) {
	var le *LengthError
	_, err := NewSecretBox(repeat(0, 10))
	if !errors.As(err, &le) {
		t.Fatalf("expected *LengthError, got %T", err)
	}
	if le.Got != 10 || le.Want != SecretBoxKeyBytes {
		t.Fatalf("LengthError fields: got=%d want=%d", le.Got, le.Want)
	}
	if !errors.Is(err, ErrLength) || !errors.Is(err, ErrCrypto) {
		t.Fatal("LengthError should unwrap to ErrLength and ErrCrypto")
	}
	if le.Error() == "" {
		t.Fatal("empty LengthError message")
	}

	var bad *BadAuthenticatorError
	sb, _ := NewSecretBox(repeat(1, 32))
	ct, _ := sb.Encrypt(repeat(2, 24), []byte("x"))
	ct[0] ^= 1
	_, err = sb.Decrypt(repeat(2, 24), ct)
	if !errors.As(err, &bad) {
		t.Fatalf("expected *BadAuthenticatorError, got %T", err)
	}
	if !errors.Is(err, ErrBadAuthenticator) || !errors.Is(err, ErrCrypto) {
		t.Fatal("BadAuthenticatorError should unwrap to ErrBadAuthenticator and ErrCrypto")
	}
	if bad.Error() == "" {
		t.Fatal("empty BadAuthenticatorError message")
	}
}
