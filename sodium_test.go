// mustHex decodes a hex literal from a published test vector, failing the test
// on a malformed literal.
func mustHex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatalf("bad hex %q: %v", s, err)
	}
	return b
}

func repeat(b byte, n int) []byte {
	out := make([]byte, n)
	for i := range out {
		out[i] = b
	}
	return out
}

// --- RandomBytes -----------------------------------------------------------

func TestRandomBytes(t *testing.T) {
	a := RandomBytes(32)
	if len(a) != 32 {
		t.Fatalf("len = %d, want 32", len(a))
	}
	if bytes.Equal(a, make([]byte, 32)) {
		t.Fatal("RandomBytes returned all zeroes")
	}
}

func TestRandomBytesPanicsOnReaderFailure(t *testing.T) {
	defer func(orig func([]byte) (int, error)) { randRead = orig }(randRead)
	randRead = func([]byte) (int, error) { return 0, errors.New("boom") }
	defer func() {
		if r := recover(); r == nil {
			t.Fatal("expected panic when the CSPRNG fails")
		}
	}()
	RandomBytes(16)
}

// --- SecretBox (XSalsa20-Poly1305) -----------------------------------------
//
// Vector: expected ciphertext generated by the C implementation of NaCl
// (golang.org/x/crypto/nacl/secretbox reference test): key = 32×0x01,
// nonce = 24×0x02, message = 64×0x03.

func TestSecretBoxVector(t *testing.T) {
	key := repeat(0x01, 32)
	nonce := repeat(0x02, 24)
	msg := repeat(0x03, 64)
	want := mustHex(t, "8442bc313f4626f1359e3b50122b6ce6fe66ddfe7d39d14e637eb4fd5b45beadab55198df6ab5368439792a23c87db70acb6156dc5ef957ac04f6276cf6093b84be77ff0849cc33e34b7254d5a8f65ad")

	sb, err := NewSecretBox(key)
	if err != nil {
		t.Fatal(err)
	}
	ct, err := sb.Encrypt(nonce, msg)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(ct, want) {
		t.Fatalf("ciphertext\n got %x\nwant %x", ct, want)
	}
	pt, err := sb.Decrypt(nonce, ct)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(pt, msg) {
		t.Fatalf("roundtrip: got %x, want %x", pt, msg)
	}
}

func TestSecretBoxErrors(t *testing.T) {
	if _, err := NewSecretBox(repeat(0, 31)); !errors.Is(err, ErrLength) {
		t.Fatalf("short key: got %v", err)
	}
	sb, _ := NewSecretBox(repeat(1, 32))
	if _, err := sb.Encrypt(repeat(2, 23), nil); !errors.Is(err, ErrLength) {
		t.Fatalf("short nonce (encrypt): got %v", err)
	}
	if _, err := sb.Decrypt(repeat(2, 23), nil); !errors.Is(err, ErrLength) {
		t.Fatalf("short nonce (decrypt): got %v", err)
	}
	ct, _ := sb.Encrypt(repeat(2, 24), []byte("hello"))
	ct[0] ^= 0xff
	if _, err := sb.Decrypt(repeat(2, 24), ct); !errors.Is(err, ErrBadAuthenticator) {
		t.Fatalf("tampered ciphertext: got %v", err)
	}
}

// --- Box (Curve25519-XSalsa20-Poly1305) ------------------------------------
//
// Vector: golang.org/x/crypto/nacl/box reference test, expected generated by
// the C implementation of NaCl. privateKey1 = 32×0x01, publicKey1 derived from
// it, privateKey2 = 32×0x02, nonce = 24×0x04, message = 64×0x03.

func TestBoxVector(t *testing.T) {
	priv1, err := NewPrivateKey(repeat(0x01, 32))
	if err != nil {
		t.Fatal(err)
	}
	priv2, _ := NewPrivateKey(repeat(0x02, 32))
	pub1 := priv1.PublicKey()
	nonce := repeat(0x04, 24)
	msg := repeat(0x03, 64)
	want := mustHex(t, "78ea30b19d2341ebbdba54180f821eec265cf86312549bea8a37652a8bb94f07b78a73ed1708085e6ddd0e943bbdeb8755079a37eb31d86163ce241164a47629c0539f330b4914cd135b3855bc2a2dfc")

	sender := NewBox(pub1, priv2)
	ct, err := sender.Encrypt(nonce, msg)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(ct, want) {
		t.Fatalf("box ciphertext\n got %x\nwant %x", ct, want)
	}
	// The recipient (owner of priv1) reconstructs the same shared key and opens.
	pub2 := priv2.PublicKey()
	recipient := NewBox(pub2, priv1)
	pt, err := recipient.Decrypt(nonce, ct)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(pt, msg) {
		t.Fatalf("box roundtrip: got %x, want %x", pt, msg)
	}
	if !bytes.Equal(sender.SharedKey(), recipient.SharedKey()) {
		t.Fatal("shared keys differ between sender and recipient")
	}
}

