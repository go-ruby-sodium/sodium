// --- SigningKey / VerifyKey (Ed25519) --------------------------------------
//
// Vectors: RFC 8032 test 1 (empty message) and test 2 (single-byte 0x72), the
// canonical Ed25519 vectors shipped in crypto/ed25519/testdata.

func TestEd25519Vectors(t *testing.T) {
	cases := []struct {
		seed, pub, msg, sig string
	}{
		{
			seed: "9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60",
			pub:  "d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a",
			msg:  "",
			sig:  "e5564300c360ac729086e2cc806e828a84877f1eb8e5d974d873e065224901555fb8821590a33bacc61e39701cf9b46bd25bf5f0595bbe24655141438e7a100b",
		},
		{
			seed: "4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb",
			pub:  "3d4017c3e843895a92b70aa74d1b7ebc9c982ccf2ec4968cc0cd55f12af4660c",
			msg:  "72",
			sig:  "92a009a9f0d4cab8720e820b5f642540a2b27b5416503f8fb3762223ebdb69da085ac1e43e15996e458f3613d0f11d8c387b2eaeb4302aeeb00d291612bb0c00",
		},
	}
	for i, c := range cases {
		sk, err := NewSigningKey(mustHex(t, c.seed))
		if err != nil {
			t.Fatalf("case %d: %v", i, err)
		}
		vk := sk.VerifyKey()
		if !bytes.Equal(vk.Bytes(), mustHex(t, c.pub)) {
			t.Fatalf("case %d: pubkey\n got %x\nwant %s", i, vk.Bytes(), c.pub)
		}
		msg := mustHex(t, c.msg)
		sig := sk.Sign(msg)
		if !bytes.Equal(sig, mustHex(t, c.sig)) {
			t.Fatalf("case %d: signature\n got %x\nwant %s", i, sig, c.sig)
		}
		if err := vk.Verify(sig, msg); err != nil {
			t.Fatalf("case %d: verify: %v", i, err)
		}
		if !bytes.Equal(sk.Seed(), mustHex(t, c.seed)) {
			t.Fatalf("case %d: seed round-trip", i)
		}
	}
}

